# Combines filings.json (where each club's accounts came from) and figures.json (the
# checked figures) into ../data/clubs.js, which the site loads.
import json, re, datetime, os
here = os.path.dirname(os.path.abspath(__file__))
filings = json.load(open(os.path.join(here, "filings.json"), encoding="utf-8"))
figures = json.load(open(os.path.join(here, "figures.json"), encoding="utf-8"))
MONTHS = {m: i + 1 for i, m in enumerate(["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"])}

def tidy(name):
    name = re.sub(r",?\s*LIMITED\s*\(THE\)|,?\s*LIMITED,?\s*\(THE\)", " LIMITED", name)
    name = name.title().replace("Plc", "PLC").replace("Afc", "AFC").replace("Qpr", "QPR").replace(" And ", " and ").replace(" ,", ",")
    if name.startswith("The ") is False and "(The)" in name:
        name = name.replace("(The)", "").strip()
    return re.sub(r"\s+", " ", name.replace(",Limited", " Limited")).strip()

clubs = []
for slug, f in filings.items():
    fig = figures[slug]
    m = re.search(r"(\d{1,2}) (\w+) (\d{4})", f["description"])
    year_end = datetime.date(int(m.group(3)), MONTHS[m.group(2)], int(m.group(1))).isoformat()
    group = "group" in f["description"].lower()
    clubs.append({
        "slug": slug,
        "name": f["name"],
        "league2425": fig["league2425"],
        "companyName": tidy(f["companyName"]),
        "companyNumber": f["companyNumber"],
        "accountsType": "Group" if group else "Company",
        "yearEnd": year_end,
        "months": fig.get("months", 12),
        "sourceUrl": f["url"],
        **{k: fig[k] for k in ["revenue", "matchday", "broadcasting", "commercial", "staffCosts", "amortisation", "otherOpCosts", "playerSales", "preTax", "prior", "pages"]},
        "mixSplit": fig.get("mixSplit") != "no",
        "notes": fig.get("notes", []),
    })
clubs.sort(key=lambda c: c["name"])
out = {"asOf": datetime.date.today().strftime("%-d %B %Y"), "season": "2026/27", "clubs": clubs}
with open(os.path.join(here, "..", "data", "clubs.js"), "w", encoding="utf-8") as fh:
    fh.write("// Generated by pipeline/build_data.py — edit pipeline/figures.json, not this file.\n")
    fh.write("// Money figures are £'000 as reported in each club's accounts.\n")
    fh.write("window.CLUB_DATA = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
print(len(clubs), "clubs written")
for c in clubs: print(f"  {c['name']:26} {c['companyName']:55} {c['yearEnd']} {c['accountsType']}")
